"""Lead-only holdout run for the four strategies that passed their dev gates.

Runs each frozen build_weights once on the full panel, then evaluates the
2024-01-02 -> 2026-10-23 holdout and the overlapping 10y/5y windows.
Development metrics are left exactly as generated by the agents.
"""
from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(r"C:\Users\27175\Desktop\quant-trader-research")
sys.path.insert(0, str(ROOT / "research"))
import bt  # noqa: E402

HERE = ROOT / "research" / "revisit"
BARS = 252 * 390
SYMS = ("QQQ", "TQQQ", "BIL")
WINDOWS = {
    "holdout": ("2024-01-02", "2026-10-23"),
    "10y": ("2017-01-03", "2026-10-23"),
    "5y": ("2021-10-25", "2026-10-23"),
}
SLUGS = ["ratio-pairs", "intraday-seasonality", "intraday-mean-reversion",
         "gap-capitulation-reversal"]


def load_mod(slug: str):
    path = HERE / slug / "strategy.py"
    spec = importlib.util.spec_from_file_location("rev_" + slug.replace("-", "_"), path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod


def pack(s: dict) -> dict:
    keys = ("cagr", "max_drawdown", "sharpe", "sortino", "volatility",
            "fills", "turnover", "exposure", "ending_equity")
    return {k: float(s[k]) for k in keys if k in s}


def bench(ts, closes, col, start):
    i = bt.start_index(ts, start)
    out = bt.benchmark(closes[i:, col], ts[i:], BARS)
    out["symbol"] = ("TQQQ", "QQQ")[col == 1]
    return out


# Each strategy is split into build (signal -> weights, the slow part, done
# once per strategy) and evaluate (one window at one slippage, fast).

def build_ratio(mod, ts, op, cl):
    w, _ = mod.build_weights(ts, op, cl)
    return w


def eval_ratio(mod, w, ts, op, cl, start, end, slip):
    r, s = mod.run_window(w, ts, op, cl, start, end, slip)
    return s


def build_seasonality(mod, ts, op, cl):
    w, _ = mod.build_weights(ts, op, cl, **mod.BASE)
    return w


def eval_seasonality(mod, w, ts, op, cl, start, end, slip):
    r = mod.simulate_window(ts, op, cl, w, (start, end), slip)
    return mod.metrics(r)


def build_meanrev(mod, ts, op, cl):
    w, _ = mod.build_weights(ts, op, cl)
    return w


def eval_meanrev(mod, w, ts, op, cl, start, end, slip):
    r, s, _, _ = mod.run_window(ts, op, cl, w, start, end, slip)
    return s


def build_gapcap(mod, ts, op, cl):
    qlow, qvol = mod.daily_extras(ts)
    w, _ = mod.build_weights(ts, op, cl, qlow, qvol)
    return w


def eval_gapcap(mod, w, ts, op, cl, start, end, slip):
    # window_metrics runs from `start` to the end of the panel.
    r, s = mod.window_metrics(ts, op, cl, w, start, slip)
    return s


RUNNERS = {
    "ratio-pairs": (build_ratio, eval_ratio),
    "intraday-seasonality": (build_seasonality, eval_seasonality),
    "intraday-mean-reversion": (build_meanrev, eval_meanrev),
    "gap-capitulation-reversal": (build_gapcap, eval_gapcap),
}


def main():
    ts, op, cl = bt.panel(SYMS, "2016-01-04", "2026-10-23", "1min", warmup_days=0)
    print(f"full panel {len(ts):,} bars {ts[0]} .. {ts[-1]}")
    for slug in SLUGS:
        print("=" * 80)
        print(slug)
        mod = load_mod(slug)
        path = HERE / slug / "result.json"
        out = json.loads(path.read_text())
        build, evaluate = RUNNERS[slug]
        # build_weights is causal and deterministic, so one build serves every
        # window and slippage level (previously it was rebuilt 9 times).
        w = build(mod, ts, op, cl)
        for name, (start, end) in WINDOWS.items():
            block = {}
            for slip in (1.0, 5.0, 10.0):
                s = evaluate(mod, w, ts, op, cl, start, end, slip)
                block[f"{int(slip)}bp"] = pack(s)
                print(f"  {name:7s} {int(slip):2d}bp  CAGR {s['cagr']*100:7.2f}%  "
                      f"DD {s['max_drawdown']*100:6.2f}%  Sharpe {s['sharpe']:5.2f}")
            out.setdefault("windows", {})[name] = block
        for name, (start, end) in WINDOWS.items():
            i = bt.start_index(ts, start)
            out.setdefault("benchmarks", {})[f"{name}_tqqq"] = bench(ts, cl, 1, start)
            out.setdefault("benchmarks", {})[f"{name}_qqq"] = bench(ts, cl, 0, start)
        out["holdout_note"] = (
            "Single lead run on the frozen weights after the dev freeze; "
            "the first holdout session starts flat, as in the dev window helpers."
        )
        path.write_text(json.dumps(out, indent=2, default=float), encoding="utf-8")
        print("  wrote", path)


if __name__ == "__main__":
    main()
