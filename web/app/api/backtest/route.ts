import { NextResponse } from "next/server";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { createHash } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { PRESETS, WINDOW_DAYS, END_DATE, type PresetStrategy } from "@/lib/presets";
import type { WindowId } from "@/lib/types";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

const execFileAsync = promisify(execFile);

type RequestBody = {
  preset?: string;
  window?: WindowId;
  benchmark?: string;
  slippageBps?: number;
  refresh?: boolean;
  strategy?: Partial<PresetStrategy>;
};

function numeric(value: unknown, fallback: number, min: number, max: number) {
  const parsed = typeof value === "number" ? value : Number(value);
  if (!Number.isFinite(parsed)) return fallback;
  return Math.min(max, Math.max(min, parsed));
}

function tomlString(value: string) {
  return JSON.stringify(value);
}

function buildConfig(presetId: string, body: RequestBody) {
  const preset = PRESETS[presetId];
  if (!preset) throw new Error(`Unknown preset '${presetId}'`);
  const window = body.window ?? preset.windows[0];
  if (!preset.windows.includes(window)) {
    throw new Error(`${preset.name} does not have a ${window} window`);
  }
  const benchmark = String(body.benchmark ?? preset.benchmark).trim();
  if (!/^[A-Z^][A-Z0-9.^-]{0,12}$/.test(benchmark)) {
    throw new Error("benchmark must be a plain ticker such as QQQ, SPY, ^NDX or ^IXIC");
  }
  const slippage = numeric(body.slippageBps, 1, 0, 100);

  const strategy: PresetStrategy = {
    ...preset.strategy,
    smaDays: Math.round(numeric(body.strategy?.smaDays, preset.strategy.smaDays, 2, 500)),
    targetVol: numeric(body.strategy?.targetVol, preset.strategy.targetVol, 0, 1),
    leverage: numeric(body.strategy?.leverage, preset.strategy.leverage, 1, 5),
    volDays: Math.round(numeric(body.strategy?.volDays, preset.strategy.volDays, 2, 252)),
    rebalanceBand: numeric(
      body.strategy?.rebalanceBand,
      preset.strategy.rebalanceBand,
      0,
      0.5,
    ),
  };

  const synthetic =
    preset.synthetic && (window === "20y" || window === "26y") ? preset.synthetic : null;

  const lines = [
    "# Generated by the local backtest lab. Do not edit by hand.",
    'broker = "sim"',
    `symbols = [${preset.symbols.map(tomlString).join(", ")}]`,
    'timeframe = "1d"',
    "poll_seconds = 600",
    "",
    "[strategy]",
    'kind = "leveraged_index"',
    `index = ${tomlString(strategy.index)}`,
    `risk_asset = ${tomlString(strategy.riskAsset)}`,
    `leverage = ${strategy.leverage}`,
    `safe_asset = ${tomlString(strategy.safeAsset)}`,
    `sma_days = ${strategy.smaDays}`,
    `target_vol = ${strategy.targetVol}`,
    `vol_days = ${strategy.volDays}`,
    `rebalance_band = ${strategy.rebalanceBand}`,
    "",
    "[risk]",
    "position_pct = 1.0",
    "max_positions = 3",
    `slippage_bps = ${slippage}`,
    "",
    "[backtest]",
    `end_date = ${tomlString(END_DATE)}`,
    `days = ${WINDOW_DAYS[window]}`,
    `benchmark = ${tomlString(benchmark)}`,
    "lag_bars = 1",
    "fill_open = true",
  ];

  if (synthetic) {
    lines.push(
      `synthetic_symbol = ${tomlString(synthetic.symbol)}`,
      `synthetic_index = ${tomlString(synthetic.index)}`,
      `synthetic_leverage = ${synthetic.leverage}`,
      `synthetic_fee_pct = ${synthetic.feePct}`,
      `synthetic_spread_pct = ${synthetic.spreadPct}`,
    );
  }

  return {
    preset,
    window,
    benchmark,
    strategy,
    slippage,
    text: `${lines.join("\n")}\n`,
  };
}

function binaryPath(root: string) {
  const name = process.platform === "win32" ? "quant-trader.exe" : "quant-trader";
  return path.join(root, "target", "release", name);
}

export async function POST(request: Request) {
  let body: RequestBody;
  try {
    body = (await request.json()) as RequestBody;
  } catch {
    return NextResponse.json({ error: "Invalid JSON body" }, { status: 400 });
  }
  if (!body.preset) {
    return NextResponse.json({ error: "preset is required" }, { status: 400 });
  }

  let config: ReturnType<typeof buildConfig>;
  try {
    config = buildConfig(body.preset, body);
  } catch (error) {
    return NextResponse.json(
      { error: error instanceof Error ? error.message : "Invalid backtest request" },
      { status: 400 },
    );
  }

  const root = process.env.QUANT_TRADER_ROOT || path.resolve(process.cwd(), "..");
  const exe = binaryPath(root);
  if (!fs.existsSync(exe)) {
    return NextResponse.json(
      {
        error:
          "Rust backtester not found. Build it first with `cargo build --release` from the repository root.",
      },
      { status: 503 },
    );
  }

  const key = createHash("sha256")
    .update(
      JSON.stringify({
        preset: body.preset,
        window: config.window,
        benchmark: config.benchmark,
        strategy: config.strategy,
        slippage: config.slippage,
      }),
    )
    .digest("hex")
    .slice(0, 20);
  const cacheDir = path.join(os.tmpdir(), "quant-trader-web");
  fs.mkdirSync(cacheDir, { recursive: true });
  const configPath = path.join(cacheDir, `${key}.toml`);
  const resultPath = path.join(cacheDir, `${key}.json`);

  const started = Date.now();
  try {
    let cached = false;
    if (!body.refresh && fs.existsSync(resultPath)) {
      cached = true;
    } else {
      fs.writeFileSync(configPath, config.text, "utf8");
      await execFileAsync(exe, ["backtest", "--config", configPath, "--json", resultPath], {
        cwd: root,
        timeout: 180_000,
        maxBuffer: 20 * 1024 * 1024,
      });
    }
    const data = JSON.parse(fs.readFileSync(resultPath, "utf8"));
    return NextResponse.json({
      data,
      cached,
      elapsedMs: Date.now() - started,
      request: {
        preset: config.preset.id,
        window: config.window,
        benchmark: config.benchmark,
        strategy: config.strategy,
        slippageBps: config.slippage,
      },
    });
  } catch (error) {
    const detail =
      error && typeof error === "object" && "stderr" in error
        ? String((error as { stderr?: unknown }).stderr ?? "")
        : error instanceof Error
          ? error.message
          : "Backtest failed";
    return NextResponse.json(
      { error: `Backtest failed: ${detail.slice(0, 2000)}` },
      { status: 500 },
    );
  }
}
